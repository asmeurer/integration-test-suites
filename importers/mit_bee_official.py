def check_transcription():
    """Reconcile the transcription against the printed problem counts
    and make sure every expression sympifies."""
    from sympy import Symbol, sympify

    x = Symbol('x')
    numbers: dict[str, set] = {}
    for rnd, num, integrand, lower, upper, answer in PROBLEMS:
        if num in numbers.setdefault(rnd, set()):
            raise ValueError('%s problem %s appears twice' % (rnd, num))
        numbers[rnd].add(num)
        f = sympify(integrand)
        if not f.has(x) and (rnd, num) not in CONSTANT_OK:
            raise ValueError('%s problem %s: integrand does not contain '
                             'x: %s' % (rnd, num, integrand))
        if (lower is None) != (upper is None):
            raise ValueError('%s problem %s: half-open bounds'
                             % (rnd, num))
        for text in (lower, upper, answer):
            if text is not None:
                sympify(text)
    for rnd, num, _reason in SKIPPED:
        if num in numbers.setdefault(rnd, set()):
            raise ValueError('%s problem %s appears twice' % (rnd, num))
        numbers[rnd].add(num)
    for rnd, expected in EXPECTED_COUNTS.items():
        have = numbers.get(rnd, set())
        if len(have) != expected:
            raise ValueError('%s: %d problems transcribed, %d printed'
                             % (rnd, len(have), expected))
        if all(isinstance(n, int) for n in have) and max(have) == expected:
            if have != set(range(1, expected + 1)):
                raise ValueError('%s: problems %s do not cover 1..%d'
                                 % (rnd, sorted(have), expected))
    unknown = set(numbers) - set(EXPECTED_COUNTS)
    if unknown:
        raise ValueError('rounds without an expected count: %s'
                         % sorted(unknown))
    for rnd, num in list(CONSTANT_OK) + list(ANSWER_OVERRIDES):
        if num not in numbers.get(rnd, set()):
            raise ValueError('override for unknown problem %s %s'
                             % (rnd, num))


def main() -> None:
    check_transcription()

    out_dir = os.path.join(HERE, 'data', 'mit_bee_official')
    os.makedirs(out_dir, exist_ok=True)

    n_definite = n_no_answer = 0
    per_round: Counter = Counter()
    overridden = []
    with open(os.path.join(out_dir, 'mit_bee_official.jsonl'), 'w',
              encoding='utf-8') as fh:
        for index, (rnd, num, integrand, lower, upper, answer) in \
                enumerate(PROBLEMS):
            if (rnd, num) in ANSWER_OVERRIDES:
                overridden.append({'round': rnd, 'problem': num,
                                   'printed': answer})
                answer = ANSWER_OVERRIDES[rnd, num]
            definite = lower is not None
            record = IntegrationTestCase(
                integrand=integrand, variable='x', suite='mit_bee_official',
                source='MIT Integration Bee %s, problem %s' % (rnd, num),
                index=index,
                lower=lower, upper=upper,
                value=answer if definite else None,
                integral=None if definite else answer)
            fh.write(record.to_json() + '\n')
            per_round[rnd] += 1
            n_definite += definite
            n_no_answer += answer is None

    report = {
        'site': SITE,
        'cases': len(PROBLEMS),
        'definite_cases': n_definite,
        'indefinite_cases': len(PROBLEMS) - n_definite,
        'cases_without_answer': n_no_answer,
        'per_round': dict(sorted(per_round.items())),
        'printed_problem_counts': EXPECTED_COUNTS,
        'answer_overrides': overridden,
        'skipped': [{'round': rnd, 'problem': num, 'reason': reason}
                    for rnd, num, reason in SKIPPED],
    }
    with open(os.path.join(out_dir, 'IMPORT_REPORT.json'), 'w',
              encoding='utf-8') as fh:
        json.dump(report, fh, indent=2)
        fh.write('\n')

    print('mit_bee_official %6d cases (%d definite, %d without answer, '
          '%d skipped)' % (len(PROBLEMS), n_definite, n_no_answer,
                           len(SKIPPED)))


if __name__ == '__main__':
    main()
