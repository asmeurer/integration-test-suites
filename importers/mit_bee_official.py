"""The MIT Integration Bee problems, transcribed from the official PDFs.

Source: the qualifier tests and bee-round problem sets posted at
https://math.mit.edu/~yyao1/integrationbee.html (one PDF per round,
under ``pdf/`` on that site).  Unlike the ``mit_bee`` suite -- Nasser
Abbasi's selection of integrands sympy 1.11.1 could not do -- this suite
is a direct transcription of every posted problem together with its
official answer, so nearly every case carries an expected result and
the corpus audit (``validate.py``) can prove the transcription against
itself.

Many of these problems are definite integrals, and some are *only*
meaningful as definite integrals (floor functions, infinite products,
symmetric-interval tricks); they use the ``lower``/``upper``/``value``
fields of the case schema.  Indefinite problems carry the boxed
antiderivative in ``integral``.

The transcription below is the auditable artifact: one tuple per
problem, in printed order, with the printed per-file problem counts
asserted so that a silently skipped problem cannot pass unnoticed.
Problems that cannot be transcribed into a sympy expression are listed
in SKIPPED with the reason, and both lists are reconciled against the
printed counts.  A handful of printed answers are provably wrong on
the sheet (sign typos and the like); those are kept verbatim in
PROBLEMS and corrected through ANSWER_OVERRIDES, so both the printed
text and the correction stay auditable.

Bee-round PDFs restart their printed numbering per sub-round
(Quarterfinal #1..#4, tiebreakers, and so on); those problems carry
sequential numbers 101, 102, ... in file order, or the printed
tiebreaker/lightning labels ('T1', 'L1') for the 2024 finals, with the
mapping recorded in the transcription comments.

Usage:
    python importers/mit_bee_official.py
"""
